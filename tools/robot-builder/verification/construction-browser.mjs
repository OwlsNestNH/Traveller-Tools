import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(process.argv[2]||'playwright');
const base=process.env.ROBOT_TEST_URL||'http://127.0.0.1:8778/tools/robot-builder/';
const out=path.resolve(process.env.ROBOT_ARTIFACTS||'verification-artifacts/robot');
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.ROBOT_BROWSER_CHANNEL?{channel:process.env.ROBOT_BROWSER_CHANNEL}:{})});
const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
const page=await context.newPage();const errors=[];const checks=[];
page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
const check=(label,ok)=>{assert.ok(ok,label);checks.push(label);};
const stage=async n=>page.locator('#stage-nav button').nth(n-1).click();
const exportDraft=async()=>{const promise=page.waitForEvent('download');await page.locator('#export-design').click();const download=await promise;return JSON.parse(await fs.readFile(await download.path(),'utf8'));};
try{
 await page.goto(base);await page.locator('#stage-nav button').first().waitFor();
 await page.locator('#robot-name').fill('Construction fixture');await stage(3);check('direct click after typing navigates once',await page.locator('#stage-title').textContent()==='Physical Options');
 await stage(3);await page.locator('#physical-category').selectOption('slot-cost-options');
 const equipment=page.locator('#field-physical-options-slot-cost-options');
 await equipment.selectOption('storage-compartment');await equipment.locator('..').getByRole('button',{name:'Add',exact:true}).click();
 const quantity=page.locator('#field-physical-optionParameters-slot-cost-options-storage-compartment-quantity');
 await quantity.selectOption('3');
 let draft=await exportDraft();check('slot allocation retained through API',draft.selections.physical.optionParameters['storage-compartment'].quantity===3);
 check('allocated slots reflected',await page.locator('#summary-metrics').textContent().then(t=>t.includes('3 / 16')));
 await quantity.selectOption('1000');
 check('over-capacity flagged',await page.locator('#design-status').textContent()==='Needs correction');
 await quantity.selectOption('3');
 await page.getByRole('button',{name:/^Remove Storage Compartment$/i}).click();
 draft=await exportDraft();check('removal clears orphan parameters',!draft.selections.physical.options.includes('storage-compartment')&&!draft.selections.physical.optionParameters['storage-compartment']);
 await page.locator('#physical-category').selectOption('weapons');
 const weaponPrefix='#field-physical-weapons-weapons-new-';
 check('body weapon hides irrelevant manipulator selector',await page.locator(weaponPrefix+'manipulatorId').count()===0);
 await page.locator(weaponPrefix+'placement').selectOption('arm');
 check('arm weapon reveals manipulator selector',await page.locator(weaponPrefix+'manipulatorId').count()===1);
 await page.locator(weaponPrefix+'manipulatorId').selectOption('base-1');
 await page.locator(weaponPrefix+'weaponId').selectOption('laser-carbine-9');
 await page.locator(weaponPrefix+'fireControl').selectOption('basic');
 await page.getByRole('button',{name:'Add weapon',exact:true}).click();
 draft=await exportDraft();const weapon=draft.selections.physical.weapons[0];
 check('weapon choices retained through API',weapon.weaponId==='laser-carbine-9'&&weapon.placement==='arm'&&weapon.manipulatorId==='base-1'&&weapon.fireControl==='basic');
 await page.screenshot({path:path.join(out,'robot-weapon-installation.png'),fullPage:true});
 await page.getByRole('button',{name:/^Remove Laser Carbine/}).click();
 draft=await exportDraft();check('weapon removal retained',draft.selections.physical.weapons.length===0);
 await stage(5);
 const packages=page.locator('#field-skills-packages');await packages.selectOption('admin-0');
 await packages.locator('..').getByRole('button',{name:'Add',exact:true}).click();
 const prefix='#field-skills-customPackages-new-';
 await page.locator(prefix+'skill').selectOption('language');
 await page.locator(prefix+'speciality').fill('Vilani');
 await page.locator(prefix+'level').selectOption('1');
 await page.getByRole('button',{name:'Add custom package',exact:true}).click();
 draft=await exportDraft();
 check('book custom skill data retained',draft.selections.skills.customPackages.some(p=>p.skill==='language'&&p.speciality==='Vilani'&&p.level===1));
 check('fixed skill retained alongside custom',draft.selections.skills.packages.includes('admin-0'));
 await page.screenshot({path:path.join(out,'robot-custom-skills.png'),fullPage:true});
 await page.locator('#save-design').click();await page.getByText('Design saved.',{exact:true}).waitFor();
 const saved=await page.evaluate(()=>localStorage.getItem('traveller.robot-builder.designs.v1'));
 await page.locator('#new-design').click();check('new design leaves saved bytes',await page.evaluate(()=>localStorage.getItem('traveller.robot-builder.designs.v1'))===saved);
 await page.locator('#robot-kind').selectOption('clone');
 await stage(1);
 check('clone has separate controls',await page.locator('#stage-content').textContent().then(t=>t.includes('Template')));
 const clone=await exportDraft();check('clone saved schema separate',clone.kind==='clone'&&!!clone.special);
 await stage(5);check('clone training visible',await page.locator('#stage-content').textContent().then(t=>/training|creche|crèche/i.test(t)));
 await page.screenshot({path:path.join(out,'robot-clone-training.png'),fullPage:true});
 await page.locator('#example-design').selectOption('steward-droid');await page.locator('#load-example').click();
 const example=await exportDraft();check('published example loads as draft',example.name.includes('Steward'));
 check('published construction and list prices remain distinct',await page.locator('#summary-metrics').textContent().then(t=>t.includes('39,800')&&t.includes('35,000')));
 check('loading example leaves saved bytes unchanged',await page.evaluate(()=>localStorage.getItem('traveller.robot-builder.designs.v1'))===saved);
 check('no runtime errors',errors.length===0);
 await fs.writeFile(path.join(out,'construction-report.json'),JSON.stringify({checks,errors},null,2));console.log('PASS '+checks.length+' construction workflow checks');
}catch(error){await page.screenshot({path:path.join(out,'construction-failure.png'),fullPage:true});await fs.writeFile(path.join(out,'construction-report.json'),JSON.stringify({checks,errors,failure:error.stack},null,2));throw error;}
finally{await context.close();await browser.close();}
