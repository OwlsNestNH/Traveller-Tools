import {createRequire} from 'node:module';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createServer} from '../server.mjs';
const require=createRequire(import.meta.url);
const {chromium}=require(process.argv[2]||'playwright');
const out=fileURLToPath(new URL('./artifacts/',import.meta.url));await mkdir(out,{recursive:true});
const server=createServer();await new Promise(r=>server.listen(0,'127.0.0.1',r));const origin='http://127.0.0.1:'+server.address().port;
const browser=await chromium.launch({headless:true,...(process.env.CHARACTER_BROWSER_CHANNEL?{channel:process.env.CHARACTER_BROWSER_CHANNEL}:{})});
const errors=[],checks=[];
try{
 for(const [name,viewport,transport] of [['desktop',{width:1440,height:1000},'http'],['mobile',{width:390,height:844},'http'],['narrow',{width:320,height:740},'in-process']]){
  const context=await browser.newContext({viewport});const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
  const engineRequests=[];page.on('request',request=>{if(new URL(request.url()).pathname.includes('/engine/'))engineRequests.push(request.url());});
  await page.goto(origin+(transport==='http'?'/?api=local':'/'));await page.getByRole('heading',{name:'Start your Traveller'}).waitFor();
  await page.locator('[name=name]').fill('Browser Test <Traveller>');
  await page.locator('[name=boons]').selectOption('3');
  await page.locator('#setup-optional-settings>summary').click();await page.locator('[name=extras][value=LCK]').check();
  await page.getByRole('button',{name:'Begin character',exact:true}).click();
  await page.getByRole('button',{name:'Roll six characteristics'}).waitFor();
  await page.getByRole('button',{name:'Roll six characteristics'}).click();
  await page.getByRole('button',{name:'Keep these characteristics'}).waitFor();
  assert.equal(await page.locator('#workspace .stat').count(),6);
  const total=await page.locator('.total').innerText();
  await page.locator('#swap-a').selectOption('0');await page.locator('#swap-b').selectOption('1');
  await page.getByRole('button',{name:'Swap scores'}).click();
  await page.waitForFunction(()=>document.querySelector('#message').textContent.startsWith('Swapped'));
  assert.equal(await page.locator('.total').innerText(),total);
  await page.screenshot({path:path.join(out,name+'-statistics.png'),fullPage:true});
  await page.getByRole('button',{name:'Keep these characteristics'}).click();await page.getByRole('heading',{name:'Choose background skills'}).waitFor();
  assert.equal(await page.locator('#sheet .stat').filter({hasText:'LCK'}).count(),1);
  assert.equal(await page.locator('#sheet .stat').filter({hasText:'PSI'}).count(),0);
  const backgroundText=await page.locator('#workspace>p').allTextContents();const count=Number(backgroundText.join(' ').match(/Choose\s+(\d+)/)?.[1]??0);
  for(let i=0;i<count;i++)await page.locator('input[name=skills]').nth(i).check();
  await page.getByRole('button',{name:'Accept background skills'}).click();await page.getByRole('heading',{name:'Before your career'}).waitFor();
  await page.getByRole('button',{name:'Go straight to careers'}).click();await page.getByRole('heading',{name:'Choose your next career'}).waitFor();
  await page.getByRole('button',{name:/Drifter.*Core/}).click();await page.locator('#career-assignment').selectOption('wanderer');
  await page.getByRole('button',{name:'Attempt this career'}).click();
  await page.waitForFunction(()=>!document.querySelector('#step-title').textContent.includes('Choose your next career'));
  const saved=await page.evaluate(()=>localStorage.getItem('traveller-character-generator.v1'));assert.ok(JSON.parse(saved).events.length>5);
  const beforeLog=await page.locator('#action-log li').count();await page.reload();await page.waitForFunction(()=>document.querySelectorAll('#action-log li').length>0);assert.equal(await page.locator('#action-log li').count(),beforeLog);
  assert.equal(await page.locator('#sheet img,#sheet script').count(),0);
  const downloadEvent=page.waitForEvent('download');await page.locator('#export').click();const download=await downloadEvent;const exported=JSON.parse(await readFile(await download.path(),'utf8'));assert.equal(exported.events.length,beforeLog);
  const horizontal=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);assert.equal(horizontal,false,name+' horizontal overflow');
  const tinyButtons=await page.locator('button:visible').evaluateAll(nodes=>nodes.filter(n=>n.getBoundingClientRect().height<43).map(n=>n.textContent));assert.deepEqual(tinyButtons,[]);
  await page.screenshot({path:path.join(out,name+'-career.png'),fullPage:true});
  await page.locator('#import').setInputFiles({name:'broken.json',mimeType:'application/json',buffer:Buffer.from('{"format":"invalid"}')});
  await page.waitForFunction(()=>document.querySelector('#message').textContent.includes('Could not load'));
  assert.equal(await page.locator('#action-log li').count(),beforeLog);
  const result=await page.locator('#workspace').innerText();assert.ok(result.length>0);
  await page.evaluate(()=>document.body.style.fontSize='36px');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false,name+' enlarged-text overflow');
  if(transport==='http')assert.deepEqual(engineRequests,[],'HTTP GUI must not download rules engine modules');
  else assert.ok(engineRequests.some(url=>url.endsWith('/engine/session.mjs')),'Static mode still uses the in-process engine');
  checks.push({viewport:name,transport,engineModuleRequests:engineRequests.length,logActions:beforeLog,pass:true});await context.close();
 }
 assert.deepEqual(errors,[]);
 await writeFile(path.join(out,'browser-results.json'),JSON.stringify({checks,errors},null,2));console.log(JSON.stringify({checks,errors}));
}finally{await browser.close();server.closeAllConnections();await new Promise(r=>server.close(r));}
