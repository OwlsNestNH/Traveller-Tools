// FNV-1a over the result identity and action identity, with no game RNG access.
// The same action always displays the same line. Different actions may collide.
export function familyTagline(band, die, actionId = '') {
  if (typeof band !== 'string' || !Number.isInteger(die) || die < 1 || die > 6) return '';
  const key = `${band}:${die}`;
  if (!Object.hasOwn(ASLAN_FAMILY_TAGLINES, key)) return '';
  const lines = ASLAN_FAMILY_TAGLINES[key];
  const identity = JSON.stringify([key, String(actionId)]);
  let hash = 0x811c9dc5;
  for (let i = 0; i < identity.length; i += 1) {
    hash = Math.imul(hash ^ identity.charCodeAt(i), 0x01000193) >>> 0;
  }
  return lines[hash % lines.length];
}
